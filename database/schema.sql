CREATE OR REPLACE FUNCTION validate_request() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM system_settings WHERE setting_key='allocations_locked' AND setting_value) THEN RAISE EXCEPTION 'Guide allocations are locked by the coordinator'; END IF;
  IF EXISTS (SELECT 1 FROM projects WHERE student_id=NEW.student_id) THEN RAISE EXCEPTION 'Student already has an approved guide'; END IF;
  IF EXISTS (SELECT 1 FROM faculty WHERE faculty_id=NEW.faculty_id AND current_students >= max_students) THEN RAISE EXCEPTION 'Faculty capacity is full'; END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER validate_request_before_insert BEFORE INSERT ON guide_requests FOR EACH ROW EXECUTE FUNCTION validate_request();

CREATE OR REPLACE FUNCTION create_project_after_accept() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status='ACCEPTED' AND OLD.status <> 'ACCEPTED' THEN
    INSERT INTO projects(student_id,faculty_id,domain_id) VALUES(NEW.student_id,NEW.faculty_id,NEW.domain_id);
    UPDATE faculty SET current_students=current_students+1 WHERE faculty_id=NEW.faculty_id;
    UPDATE guide_requests SET status='REJECTED' WHERE student_id=NEW.student_id AND request_id<>NEW.request_id AND status='PENDING';
  END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER create_project_after_accept AFTER UPDATE ON guide_requests FOR EACH ROW EXECUTE FUNCTION create_project_after_accept();

-- The faculty row lock prevents simultaneous approvals from exceeding capacity.
CREATE OR REPLACE PROCEDURE accept_guide_request(p_request_id INTEGER, p_faculty_id INTEGER) LANGUAGE plpgsql AS $$
DECLARE request_row guide_requests%ROWTYPE;
BEGIN
  SELECT * INTO request_row FROM guide_requests WHERE request_id=p_request_id AND faculty_id=p_faculty_id AND status='PENDING' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Request is unavailable'; END IF;
  PERFORM 1 FROM faculty WHERE faculty_id=p_faculty_id AND current_students < max_students FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Faculty capacity is full'; END IF;
  IF EXISTS (SELECT 1 FROM projects WHERE student_id=request_row.student_id) THEN RAISE EXCEPTION 'Student already has an approved guide'; END IF;
  UPDATE guide_requests SET status='ACCEPTED' WHERE request_id=p_request_id;
END; $$;

CREATE VIEW faculty_availability AS SELECT f.faculty_id,u.name,u.email,f.department,f.max_students,f.current_students,(f.max_students-f.current_students) seats_left FROM faculty f JOIN users u ON u.id=f.faculty_id;
CREATE VIEW allocation_report AS SELECT u.name faculty,COUNT(p.project_id) allocated_students FROM faculty f JOIN users u ON u.id=f.faculty_id LEFT JOIN projects p ON p.faculty_id=f.faculty_id GROUP BY f.faculty_id,u.name;

