-- Run this file after creating a database named faculty_guide_db in pgAdmin.
-- It is written for PostgreSQL 14+.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL, email VARCHAR(120) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(10) NOT NULL CHECK (role IN ('STUDENT','FACULTY','ADMIN')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE students (
  student_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  registration_no VARCHAR(30) NOT NULL UNIQUE, department VARCHAR(80) NOT NULL,
  semester INTEGER NOT NULL CHECK (semester > 0)
);
CREATE TABLE faculty (
  faculty_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  department VARCHAR(80) NOT NULL, max_students INTEGER NOT NULL DEFAULT 5 CHECK (max_students >= 0),
  current_students INTEGER NOT NULL DEFAULT 0 CHECK (current_students >= 0 AND current_students <= max_students)
);
CREATE TABLE domains (domain_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, domain_name VARCHAR(80) NOT NULL UNIQUE);
CREATE TABLE faculty_domains (
  faculty_id INTEGER NOT NULL REFERENCES faculty(faculty_id) ON DELETE CASCADE,
  domain_id INTEGER NOT NULL REFERENCES domains(domain_id) ON DELETE CASCADE, PRIMARY KEY (faculty_id, domain_id)
);
CREATE TABLE guide_requests (
  request_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES students(student_id), faculty_id INTEGER NOT NULL REFERENCES faculty(faculty_id),
  domain_id INTEGER NOT NULL REFERENCES domains(domain_id), request_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  status VARCHAR(10) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','ACCEPTED','REJECTED')),
  UNIQUE (student_id, faculty_id, domain_id)
);
CREATE TABLE projects (
  project_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(180) NOT NULL DEFAULT 'Untitled Project', description TEXT,
  student_id INTEGER NOT NULL UNIQUE REFERENCES students(student_id), faculty_id INTEGER NOT NULL REFERENCES faculty(faculty_id),
  domain_id INTEGER NOT NULL REFERENCES domains(domain_id),
  status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','COMPLETED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE milestones (
  milestone_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id INTEGER NOT NULL REFERENCES projects(project_id) ON DELETE CASCADE,
  title VARCHAR(150) NOT NULL, submission_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  status VARCHAR(20) NOT NULL DEFAULT 'SUBMITTED' CHECK (status IN ('SUBMITTED','REVIEWED','REVISION_REQUIRED')), faculty_remark TEXT
);
CREATE TABLE announcements (
  announcement_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, author_id INTEGER NOT NULL REFERENCES users(id),
  title VARCHAR(150) NOT NULL, body TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE system_settings (setting_key VARCHAR(50) PRIMARY KEY, setting_value BOOLEAN NOT NULL);
